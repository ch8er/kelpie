"""Optional root-cause section of the daily report, written by an LLM (``[report.llm]``).

The only place Kelpie calls an LLM, and never in the control loop: it runs after the
deterministic report is built, adds one section to its Markdown, and changes nothing else
(not the summary sent to the channels, not the numbers). Off unless ``[report.llm]`` is
configured; the report is complete without it.

**What leaves the host.** Only aggregates of the report, built here from fields Kelpie
computes itself: rule names and causes, hours, dollars, counts, severities, metric names
and values, and task ids that look like ids. Never task titles or bodies, block reasons,
alert texts, commands or command prefixes, tool output, fix notes or people's names:
agents control most of that text (it could carry instructions to the model) and some of
it is private. The section lists what the model saw.

**What comes back** is shown as generated text, marked as such, as a quote; images,
links and HTML in it are neutralised. A failure (no key, a timeout, an HTTP error) is a
one-line note in the section, never a failed report.

Providers: ``anthropic`` (Messages API) and ``openai`` (Chat Completions, also any
compatible endpoint through ``base_url``, e.g. a model on the same host). The API key is
read from the environment (``api_key_env``), never from the config file.
"""

from __future__ import annotations

import json
import logging
import math
import os
import re
import urllib.parse
from collections.abc import Mapping
from dataclasses import dataclass, replace
from datetime import timedelta
from typing import Any, Protocol

from kelpie import net
from kelpie.core.serde import parse_duration
from kelpie.report.daily import DailyReport
from kelpie.report.sections import Section

log = logging.getLogger(__name__)

PROVIDERS: Mapping[str, tuple[str, str]] = {  # name -> (default base_url, default key env)
    "anthropic": ("https://api.anthropic.com", "ANTHROPIC_API_KEY"),
    "openai": ("https://api.openai.com", "OPENAI_API_KEY"),
}
KEYS = frozenset({"provider", "model", "api_key_env", "base_url", "timeout", "max_tokens"})
ANTHROPIC_VERSION = "2023-06-01"
MAX_RESPONSE_BYTES = 256 * 1024
MAX_TEXT = 4000  # characters of generated text shown
MAX_LINES = 40
MAX_ITEMS = 10  # per list in the digest
MAX_IDS = 5  # task ids per line
TITLE = "Root causes (generated by an LLM)"
NOT_SENT = (
    "Not sent: task titles and bodies, block reasons, alert texts, commands, tool output, "
    "fix notes, people's names."
)
SYSTEM = (
    "You are a site reliability engineer reviewing one day of an AI agent farm. The user "
    "message is JSON that a deterministic monitor (Kelpie) computed for that day: hours "
    "lost per rule and cause, open alerts, what the monitor did or would have done, "
    "people's queues, repeated huge tool outputs, and before/after measurements of fixes. "
    "Find the most likely root causes that connect these numbers, say which numbers point "
    "to each, and suggest at most three things to check or change, most valuable first. "
    "Use only the data given; say so when it is not enough. Plain text, no Markdown, at "
    "most 15 lines."
)

_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:#/-]{0,63}")
_NAME = re.compile(r"[a-z0-9_:.-]{1,64}")  # rule names, causes, kinds, metric units
_LOOPBACK = frozenset({"localhost", "127.0.0.1", "::1"})


@dataclass(frozen=True, slots=True)
class LlmSettings:
    provider: str
    model: str
    api_key_env: str
    base_url: str
    timeout: timedelta = timedelta(seconds=60)
    max_tokens: int = 1000


def load_llm(section: Any) -> LlmSettings | None:
    """Parse ``[report.llm]`` (None when absent); raises ValueError naming the bad key."""
    if section is None:
        return None
    if not isinstance(section, Mapping):
        raise ValueError("[report.llm] must be a table")
    if extra := set(section) - KEYS:
        raise ValueError(f"unknown [report.llm] keys: {sorted(extra)}")
    provider = section.get("provider")
    if provider not in PROVIDERS:
        raise ValueError(f"[report.llm] provider must be one of {sorted(PROVIDERS)}")
    model = section.get("model")
    if not isinstance(model, str) or not model.strip():
        raise ValueError("[report.llm] model is required, e.g. a model id of the provider")
    base, key_env = PROVIDERS[provider]
    env = section.get("api_key_env", key_env)
    if not isinstance(env, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", env):
        raise ValueError("[report.llm] api_key_env must be an environment variable name")
    url = section.get("base_url", base)
    if not isinstance(url, str) or not _valid_base(url):
        raise ValueError(
            "[report.llm] base_url must be an https URL (http only on localhost), "
            "without credentials, query or fragment"
        )
    raw = section.get("timeout", "60s")
    try:
        timeout = parse_duration(raw) if isinstance(raw, str) else None
    except ValueError:
        timeout = None
    if timeout is None or not timedelta(0) < timeout <= timedelta(minutes=10):
        raise ValueError('[report.llm] timeout must be a duration up to 10m, e.g. "60s"')
    tokens = section.get("max_tokens", 1000)
    if isinstance(tokens, bool) or not isinstance(tokens, int) or not 1 <= tokens <= 32000:
        raise ValueError("[report.llm] max_tokens must be an integer from 1 to 32000")
    return LlmSettings(provider, model.strip(), env, url.rstrip("/"), timeout, tokens)


def _valid_base(url: str) -> bool:
    try:
        parts = urllib.parse.urlsplit(url)
    except ValueError:
        return False
    if parts.username or parts.password or parts.query or parts.fragment or not parts.hostname:
        return False
    return parts.scheme == "https" or (parts.scheme == "http" and parts.hostname in _LOOPBACK)


# --- what the model sees ----------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Digest:
    data: dict[str, Any]  # sent as JSON
    seen: tuple[str, ...]  # what it holds, for the reader


def digest(report: DailyReport) -> Digest:
    """The aggregates of ``report`` the model may see. Pure; see the module docstring."""
    data: dict[str, Any] = {
        "day": report.day.isoformat(),
        "completed_tasks": len(report.completed),
        "spend_usd": _num(report.spend.usd) if report.priced else None,
        "hours_lost": [
            {
                "rule": _name(c.rule),
                "cause": _name(c.cause),
                "hours": _num(c.hours),
                "usd": _num(c.spend.usd) if report.priced else None,
                "tasks": len(c.tasks),
                "task_ids": _ids(c.tasks),
            }
            for c in report.chaos[:MAX_ITEMS]
        ],
        "actions": [
            {
                "what": label,
                "rule": _name(f.rule),
                "kind": _name(str(f.kind)),
                "count": f.count,
                **({"outcome": _name(str(f.outcome))} if f.outcome is not None else {}),
            }
            for label, lines in (
                ("done", report.fixed),
                ("would_do_in_act_mode", report.would_fix),
                ("could_not_do", report.not_done),
            )
            for f in lines[:MAX_ITEMS]
        ],
        "open_alerts": [
            {
                "rule": _name(o.state.rule),
                "severity": _name(str(o.state.severity)),
                "open_hours": _num(o.open_hours),
                "escalation_level": o.state.level,
                **({"task_id": i} if (i := _id(o.state.task_id)) else {}),
            }
            for o in report.open_states[:MAX_ITEMS]
        ],
        "people_queues": [
            {
                "person": f"person-{n}",  # not their name
                "agent_hours_waited": _num(i.cost_hours),
                "items": len(i.tasks),
                "agent_tasks_held": i.blocked_agent_tasks,
            }
            for n, i in enumerate(report.inbox[:MAX_ITEMS], 1)
        ],
        "huge_output_offenders": [
            {
                "filter": _name(r.filter.name),
                "role": _name(r.group.role or "agents"),
                "days_above_threshold": len(r.group.hot_days),
                "tasks": len(r.group.tasks),
            }
            for r in report.offenders[:MAX_ITEMS]
        ],
        "fix_checks": [
            {
                "rule": _name(v.event.rule) if v.event.rule else None,
                "kind": _name(str(v.event.kind)),
                "after_hours": _num(v.after.total_seconds() / 3600),
                "metrics": [
                    {
                        "name": _name(m.name.split(" (")[0].replace(" ", "_")),
                        "unit": _name(m.unit.replace(" ", "_")),
                        "before": _num(m.before),
                        "after": _num(m.after),
                        "small_sample": m.small,
                    }
                    for m in v.metrics
                ],
            }
            for v in report.verifications[:MAX_ITEMS]
        ],
    }
    seen = (
        f"Data it saw: hours lost ({len(data['hours_lost'])} lines), Kelpie's actions "
        f"({len(data['actions'])}), open alerts ({len(data['open_alerts'])}), people's "
        f"queues ({len(data['people_queues'])}, without names), huge-output offenders "
        f"({len(data['huge_output_offenders'])}), fix checks ({len(data['fix_checks'])}); "
        "rule names, causes, hours, dollars, counts and task ids only.",
        NOT_SENT,
    )
    return Digest(data, seen)


def _num(value: float | None) -> float | None:
    return round(value, 2) if value is not None and math.isfinite(value) else None


def _name(value: str) -> str:
    """Rule names, causes, kinds: Kelpie's own words; anything else is withheld."""
    text = value.strip().lower()
    return text if _NAME.fullmatch(text) else "other"


def _id(value: str | None) -> str | None:
    return value if value is not None and _ID.fullmatch(value) else None


def _ids(values: tuple[str, ...]) -> list[str]:
    return [i for v in values[:MAX_IDS] if (i := _id(v))]


# --- the call ---------------------------------------------------------------------------


class Llm(Protocol):
    def complete(self, system: str, prompt: str) -> str: ...


class LlmError(Exception):
    """A failed call; the message is safe to show (no key, no body)."""


@dataclass(frozen=True, slots=True)
class HttpLlm:
    settings: LlmSettings
    key: str

    def complete(self, system: str, prompt: str) -> str:
        s = self.settings
        if s.provider == "anthropic":
            path = "/v1/messages"
            headers = {
                "x-api-key": self.key,
                "anthropic-version": ANTHROPIC_VERSION,
                "content-type": "application/json",
            }
            body: dict[str, Any] = {
                "model": s.model,
                "max_tokens": s.max_tokens,
                "system": system,
                "messages": [{"role": "user", "content": prompt}],
            }
        else:
            path = "/v1/chat/completions"
            headers = {"authorization": f"Bearer {self.key}", "content-type": "application/json"}
            body = {
                "model": s.model,
                "max_completion_tokens": s.max_tokens,
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": prompt},
                ],
            }
        if not net.valid_header_value(self.key):
            raise LlmError(f"the key in ${s.api_key_env} is not a valid header value")
        prefix = urllib.parse.urlsplit(s.base_url).path.rstrip("/")
        try:
            response = net.post(
                s.base_url,
                prefix + path,
                headers,
                json.dumps(body).encode(),
                s.timeout.total_seconds(),
                MAX_RESPONSE_BYTES,
                proxy=s.base_url.startswith("https:"),
            )
        except net.RequestError as exc:
            raise LlmError(f"{exc.cause}: {exc.detail}") from None
        if not 200 <= response.status < 300:
            raise LlmError(f"HTTP {response.status}")
        try:
            return _text(s.provider, json.loads(response.body))
        except (ValueError, KeyError, IndexError, TypeError):
            raise LlmError("unexpected response") from None


def _text(provider: str, answer: Any) -> str:
    if provider == "anthropic":
        parts = [b["text"] for b in answer["content"] if b.get("type") == "text"]
        return "\n".join(parts)
    content = answer["choices"][0]["message"]["content"]
    if not isinstance(content, str):
        raise TypeError("content")
    return content


# --- the section ------------------------------------------------------------------------


def root_cause_section(report: DailyReport, settings: LlmSettings, client: Llm) -> Section:
    found = digest(report)
    label = f"{settings.provider}/{settings.model}"
    try:
        text = client.complete(SYSTEM, json.dumps(found.data, separators=(",", ":")))
    except Exception as exc:  # never fail the report
        reason = str(exc) if isinstance(exc, LlmError) else type(exc).__name__
        log.warning("LLM root-cause section failed: %s", reason)
        return Section(TITLE, (f"Not available today ({label}: {reason}).",))
    lines = _quote(text)
    if not lines:
        return Section(TITLE, (f"Not available today ({label}: empty answer).",))
    return Section(
        TITLE,
        (
            f"_Written by {_plain(label)} from the aggregates below; not checked by "
            "Kelpie. Treat it as a hypothesis, not a finding._",
            "",
            *lines,
            "",
            *found.seen,
        ),
    )


def _plain(text: str) -> str:
    """Generated or configured text, safe to put in the Markdown: no HTML, images or
    links, no control characters."""
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", "", text)
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return re.sub(r"(!?)\[", r"\\\1[", text).replace("](", "]\\(")


def _quote(text: str) -> list[str]:
    lines = [_plain(line.rstrip()) for line in text.strip()[:MAX_TEXT].splitlines()]
    shown = lines[:MAX_LINES]
    if len(lines) > MAX_LINES:
        shown.append("...")
    return [f"> {line}" if line else ">" for line in shown]


def with_root_cause(
    report: DailyReport,
    settings: LlmSettings | None,
    client: Llm | None = None,
    env: Mapping[str, str] = os.environ,
) -> DailyReport:
    """``report`` with the root-cause section appended (unchanged without ``settings``).
    ``client`` defaults to the provider's HTTP API with the key from ``env``."""
    if settings is None:
        return report
    if client is None:
        key = env.get(settings.api_key_env, "").strip()
        if not key:
            note = f"Not available today: no API key in ${settings.api_key_env}."
            return replace(report, sections=(*report.sections, Section(TITLE, (note,))))
        client = HttpLlm(settings, key)
    section = root_cause_section(report, settings, client)
    return replace(report, sections=(*report.sections, section))
