"""Optional root-cause section of the daily report, written by an LLM (``[report.llm]``).

The only place Kelpie calls an LLM, and never in the control loop: ``kelpie.report.run``
calls it after the deterministic report is built; it adds one section to the Markdown and
changes nothing else (not the summary sent to the channels, not the numbers). Off unless
``[report.llm]`` is configured (:func:`kelpie.report.config.load_llm`); the report is
complete without it. ``kelpie.app``, ``kelpie.server``, core and rules never import this
module (import-linter and ``tests/test_architecture.py`` hold that line).

**What leaves the host.** Only aggregates of the report, built here from values Kelpie
computes itself: rule names, causes, action kinds, outcomes, severities, metric names and
units (each from a fixed vocabulary, else ``other``), hours, dollars, counts and escalation
levels. Tasks are ``task-1``, ``task-2``...; people ``person-1``...; the real ids never
leave and are put back into the answer here. Never sent: task titles, bodies or ids, block
reasons, alert texts, commands, tool output, fix notes, roles, people's names. Agents
control most of that text (it could carry instructions to the model) and some of it is
private. The section lists what the model saw, also when the call failed.

**What comes back** is shown as generated text, marked as such, as a quote; HTML,
images, links, code spans and Markdown escapes are neutralised and URLs and email
addresses defanged, the restored task ids with the rest. A failure (no key,
a timeout, an HTTP error) is a note in the section, never a failed report.
"""

from __future__ import annotations

import json
import logging
import math
import os
import re
import unicodedata
import urllib.parse
from collections.abc import Mapping
from dataclasses import dataclass, field, replace
from typing import Any, Protocol

from kelpie import net
from kelpie.report.config import LlmSettings
from kelpie.report.daily import CHAOS_CAUSES, DailyReport
from kelpie.report.sections import Section

log = logging.getLogger(__name__)

ANTHROPIC_VERSION = "2023-06-01"
MAX_RESPONSE_BYTES = 256 * 1024
MAX_TEXT = 4000  # characters of generated text shown
MAX_LINES = 40
MAX_ITEMS = 10  # per list in the digest
MAX_IDS = 5  # tasks per line
TITLE = "Root causes (generated by an LLM)"
SAW = (
    "Data the model saw: hours lost per rule and cause, Kelpie's actions (rule, kind, "
    "outcome, count), open alerts (rule, severity, hours open, escalation level), people's "
    "queues (agent-hours, counts), huge-output offenders (filter, days, count) and fix "
    "checks (metric names and values), with tasks as task-1, task-2... and people as "
    "person-1, person-2..."
)
NOT_SENT = (
    "Not sent: task titles, bodies and ids, block reasons, alert texts, commands, tool "
    "output, fix notes, roles, people's names."
)
SYSTEM = (
    "You are a site reliability engineer reviewing one day of an AI agent farm. The user "
    "message is JSON that a deterministic monitor (Kelpie) computed for that day: hours "
    "lost per rule and cause, open alerts, what the monitor did or would have done, "
    "people's queues, repeated huge tool outputs, and before/after measurements of fixes. "
    "Tasks are named task-1, task-2 and so on. Find the most likely root causes that "
    "connect these numbers, say which numbers point to each, and suggest at most three "
    "things to check or change, most valuable first. Use only the data given; say so when "
    "it is not enough. Plain text, no Markdown, at most 15 lines."
)

_NAME = re.compile(r"[a-z0-9_:.-]{1,64}")  # rule names, action kinds, outcomes, severities
_CAUSES = frozenset(CHAOS_CAUSES.values())
_UNITS = frozenset({"h/day", "tokens/day", "/day", "min", "tokens", "share"})  # verify.py
_ALIAS = re.compile(r"\btask-(\d{1,4})\b")


@dataclass(frozen=True, slots=True)
class Digest:
    data: dict[str, Any]  # sent as JSON
    aliases: Mapping[str, str]  # task-N -> the real task id (never sent)


class _Tasks:
    """Pseudonyms for task ids: the model sees ``task-N`` only."""

    def __init__(self) -> None:
        self.aliases: dict[str, str] = {}
        self._by_id: dict[str, str] = {}

    def __call__(self, task_id: str | None) -> str | None:
        if not task_id:
            return None
        if task_id not in self._by_id:
            alias = f"task-{len(self._by_id) + 1}"
            self._by_id[task_id] = alias
            self.aliases[alias] = task_id
        return self._by_id[task_id]


def digest(report: DailyReport) -> Digest:
    """The aggregates of ``report`` the model may see. Pure; see the module docstring."""
    tasks = _Tasks()
    data: dict[str, Any] = {
        "day": report.day.isoformat(),
        "completed_tasks": len(report.completed),
        "spend_usd": _num(report.spend.usd) if report.priced else None,
        "hours_lost": [
            {
                "rule": _name(c.rule),
                "cause": c.cause if c.cause in _CAUSES else "other",
                "hours": _num(c.hours),
                "usd": _num(c.spend.usd) if report.priced else None,
                "tasks": len(c.tasks),
                "examples": [tasks(t) for t in c.tasks[:MAX_IDS]],
            }
            for c in report.chaos[:MAX_ITEMS]
        ],
        "actions": [
            {
                "what": label,
                "rule": _name(f.rule),
                "kind": _name(str(f.kind)),
                "count": f.count,
                **({"outcome": _name(str(f.outcome))} if f.outcome is not None else {}),
            }
            for label, lines in (
                ("done", report.fixed),
                ("would_do_in_act_mode", report.would_fix),
                ("could_not_do", report.not_done),
            )
            for f in lines[:MAX_ITEMS]
        ],
        "open_alerts": [
            {
                "rule": _name(o.state.rule),
                "severity": _name(str(o.state.severity)),
                "open_hours": _num(o.open_hours),
                "escalation_level": o.state.level,
                **({"task": a} if (a := tasks(o.state.task_id)) else {}),
            }
            for o in report.open_states[:MAX_ITEMS]
        ],
        "people_queues": [
            {
                "person": f"person-{n}",
                "agent_hours_waited": _num(i.cost_hours),
                "items": len(i.tasks),
                "agent_tasks_held": i.blocked_agent_tasks,
            }
            for n, i in enumerate(report.inbox[:MAX_ITEMS], 1)
        ],
        "huge_output_offenders": [
            {
                "filter": _name(r.filter.name),
                "days_above_threshold": len(r.group.hot_days),
                "tasks": len(r.group.tasks),
            }
            for r in report.offenders[:MAX_ITEMS]
        ],
        "fix_checks": [
            {
                "rule": _name(v.event.rule) if v.event.rule else None,
                "kind": _name(v.event.kind),
                "after_hours": _num(v.after.total_seconds() / 3600),
                "metrics": [
                    {
                        "name": _name(m.name.split(" (")[0].replace(" ", "_")),
                        "unit": m.unit if m.unit in _UNITS else "other",
                        "before": _num(m.before),
                        "after": _num(m.after),
                        "small_sample": m.small,
                    }
                    for m in v.metrics
                ],
            }
            for v in report.verifications[:MAX_ITEMS]
        ],
    }
    return Digest(data, tasks.aliases)


def _num(value: float | None) -> float | None:
    return round(value, 2) if value is not None and math.isfinite(value) else None


def _name(value: str) -> str:
    """Rule names, kinds, outcomes: Kelpie's own words; anything else is withheld."""
    text = value.strip().lower()
    return text if _NAME.fullmatch(text) else "other"


# --- the call ---------------------------------------------------------------------------


class Llm(Protocol):
    def complete(self, system: str, prompt: str) -> str: ...


class LlmError(Exception):
    """A failed call; the message is safe to show (no key, no body)."""


@dataclass(frozen=True, slots=True)
class HttpLlm:
    """The provider's HTTP API through :mod:`kelpie.net` (one deadline, no redirects, a
    response cap). ``key`` None sends none (a server on this host)."""

    settings: LlmSettings
    key: str | None = field(default=None, repr=False)

    def complete(self, system: str, prompt: str) -> str:
        s = self.settings
        headers = {"content-type": "application/json"}
        if s.provider == "anthropic":
            path = "/v1/messages"
            headers["anthropic-version"] = ANTHROPIC_VERSION
            if self.key is not None:
                headers["x-api-key"] = self.key
            body: dict[str, Any] = {
                "model": s.model,
                "max_tokens": s.max_tokens,
                "system": system,
                "messages": [{"role": "user", "content": prompt}],
            }
        else:
            path = "/v1/chat/completions"
            if self.key is not None:
                headers["authorization"] = f"Bearer {self.key}"
            # OpenAI's API takes max_completion_tokens; compatible servers often only
            # max_tokens.
            limit = "max_completion_tokens" if s.default_endpoint else "max_tokens"
            body = {
                "model": s.model,
                limit: s.max_tokens,
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": prompt},
                ],
            }
        if self.key is not None and not net.valid_header_value(self.key):
            raise LlmError(f"the key in ${s.api_key_env} is not a valid header value")
        prefix = urllib.parse.urlsplit(s.base_url).path.rstrip("/")
        try:
            response = net.post(
                s.base_url,
                prefix + path,
                headers,
                json.dumps(body).encode(),
                s.timeout.total_seconds(),
                MAX_RESPONSE_BYTES,
                proxy=s.base_url.startswith("https:"),
            )
        except net.RequestError as exc:
            raise LlmError(f"{exc.cause}: {exc.detail}") from None
        if not 200 <= response.status < 300:
            raise LlmError(f"HTTP {response.status}")
        try:
            return _text(s.provider, json.loads(response.body))
        except (ValueError, KeyError, IndexError, TypeError, AttributeError):
            raise LlmError("unexpected response") from None


def _text(provider: str, answer: Any) -> str:
    if provider == "anthropic":
        blocks = answer["content"]
        return "\n".join(
            b["text"] for b in blocks if isinstance(b, dict) and b.get("type") == "text"
        )
    content = answer["choices"][0]["message"]["content"]
    if not isinstance(content, str):
        raise TypeError("content")
    return content


# --- the section ------------------------------------------------------------------------


def root_cause_section(report: DailyReport, settings: LlmSettings, client: Llm) -> Section:
    found = digest(report)
    label = _code(f"{settings.provider}/{settings.model}")
    try:
        text = client.complete(SYSTEM, json.dumps(found.data, separators=(",", ":")))
    except Exception as exc:  # never fail the report
        reason = str(exc) if isinstance(exc, LlmError) else type(exc).__name__
        log.warning("LLM root-cause section failed: %s", reason)
        return Section(TITLE, (f"Not available today ({label}: {_plain(reason)}).", SAW))
    lines = _quote(text, found.aliases)
    if not lines:
        return Section(TITLE, (f"Not available today ({label}: empty answer).", SAW))
    return Section(
        TITLE,
        (
            f"Written by {label} from the aggregates below; not checked by Kelpie. Treat "
            "it as a hypothesis, not a finding.",
            "",
            *lines,
            "",
            SAW,
            NOT_SENT,
        ),
    )


def _code(text: str) -> str:
    """Configured text (a model id) as a code span."""
    return "`" + _strip_controls(text).replace("`", "'") + "`"


def _strip_controls(text: str) -> str:
    """No control or format characters (bidi overrides, zero-width), except tabs."""
    return "".join(c for c in text if c == "\t" or unicodedata.category(c) not in {"Cc", "Cf"})


def _plain(text: str) -> str:
    """Untrusted text, safe in Markdown: no HTML, images, links, code spans or escapes that
    could turn into one; URLs and email addresses defanged (``https[:]//``, ``www[.]``,
    ``a[@]b``) so renderers do not link them."""
    text = _strip_controls(text).replace("\\", "\\\\").replace("`", "\\`")
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("[", "\\[").replace("]", "\\]")
    text = re.sub(r"(?i)\b([a-z][a-z0-9+.-]*)://", r"\1[:]//", text)
    text = re.sub(r"(?i)\bwww\.", "www[.]", text)
    return re.sub(r"(?<=[\w.+-])@(?=[\w-])", "[@]", text)


def _quote(text: str, aliases: Mapping[str, str]) -> list[str]:
    raw = text.strip()[:MAX_TEXT].splitlines()
    lines = [_plain(_unalias(line.rstrip(), aliases)) for line in raw]
    shown = lines[:MAX_LINES]
    if len(lines) > MAX_LINES:
        shown.append("...")
    return [f"> {line}" if line else ">" for line in shown]


def _unalias(line: str, aliases: Mapping[str, str]) -> str:
    """Put the real task ids back, before :func:`_plain` (they are agents' text: escaped
    and defanged with the rest of the line)."""
    return _ALIAS.sub(lambda m: aliases.get(m.group(0), m.group(0)), line)


def with_root_cause(
    report: DailyReport,
    settings: LlmSettings | None,
    client: Llm | None = None,
    env: Mapping[str, str] = os.environ,
) -> DailyReport:
    """``report`` with the root-cause section appended (unchanged without ``settings``).
    ``client`` defaults to the provider's HTTP API with the key from ``env``."""
    if settings is None:
        return report
    if client is None:
        key = None
        if settings.api_key_env is not None:
            key = env.get(settings.api_key_env, "").strip()
            if not key:
                note = f"Not available today: no API key in ${settings.api_key_env}."
                return replace(report, sections=(*report.sections, Section(TITLE, (note,))))
        client = HttpLlm(settings, key)
    section = root_cause_section(report, settings, client)
    return replace(report, sections=(*report.sections, section))
